/**
 * ITEM 369-IR LEG 1 — TWO-FILE PDF DELIVERY for the Incident Response Playbook.
 *
 * One generation run yields TWO downloadable artifacts, each rendered here:
 *
 *   A. `standing_playbook`   — the pre-incident reference. Fourteen sections in
 *      the builder's locked `section_order`, the EDPB Art. 33 template field
 *      mapping rendered inside the statutory notification section, and the
 *      authority exhibit rendered LAST, immediately before the universal
 *      disclaimer that the caller appends.
 *
 *   B. `incident_worksheet`  — the blank forms. NO exhibit, no analysis, no
 *      pre-filled cell. The universal disclaimer is likewise the caller's final
 *      element.
 *
 * The universal disclaimer is NOT emitted here: `applyUniversalDisclaimerHtml`
 * in the caller appends it exactly once per document, as the final element.
 */

